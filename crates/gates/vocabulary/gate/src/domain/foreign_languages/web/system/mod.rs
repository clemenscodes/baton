impl TryFrom<WebSystem> for ForeignLanguage {
    type Error = Error;

    fn try_from(_: WebSystem) -> Result<Self, Self::Error> {
        let foreign_name_text = WebSystem::NAME;
        let foreign_name = ForeignName::from(foreign_name_text);
        let name_texts = WebSystem::NAMES;
        Self::try_from((foreign_name, name_texts))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_name_of_web_system_is_a_name() {
        let web_system = WebSystem;

        let foreign_language = ForeignLanguage::try_from(web_system);

        let error = foreign_language.err();
        let expectation = None;
        assert_eq!(error, expectation);
    }
}
