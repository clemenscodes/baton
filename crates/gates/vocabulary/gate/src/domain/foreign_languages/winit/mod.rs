impl TryFrom<Winit> for ForeignLanguage {
    type Error = Error;

    fn try_from(_: Winit) -> Result<Self, Self::Error> {
        let foreign_name_text = Winit::NAME;
        let foreign_name = ForeignName::from(foreign_name_text);
        let name_texts = Winit::NAMES;
        Self::try_from((foreign_name, name_texts))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_name_of_winit_is_a_name() {
        let winit = Winit;

        let foreign_language = ForeignLanguage::try_from(winit);

        let error = foreign_language.err();
        let expectation = None;
        assert_eq!(error, expectation);
    }
}
