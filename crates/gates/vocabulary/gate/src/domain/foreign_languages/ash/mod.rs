impl TryFrom<Ash> for ForeignLanguage {
    type Error = Error;

    fn try_from(_: Ash) -> Result<Self, Self::Error> {
        let foreign_name_text = Ash::NAME;
        let foreign_name = ForeignName::from(foreign_name_text);
        let name_texts = Ash::NAMES;
        Self::try_from((foreign_name, name_texts))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_name_of_ash_is_a_name() {
        let ash = Ash;

        let foreign_language = ForeignLanguage::try_from(ash);

        let error = foreign_language.err();
        let expectation = None;
        assert_eq!(error, expectation);
    }
}
