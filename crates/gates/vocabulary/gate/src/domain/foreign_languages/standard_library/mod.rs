impl TryFrom<StandardLibrary> for ForeignLanguage {
    type Error = Error;

    fn try_from(_: StandardLibrary) -> Result<Self, Self::Error> {
        let foreign_name_text = StandardLibrary::NAME;
        let foreign_name = ForeignName::from(foreign_name_text);
        let name_texts = StandardLibrary::NAMES;
        Self::try_from((foreign_name, name_texts))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_name_of_the_standard_library_is_a_name() {
        let standard_library = StandardLibrary;

        let foreign_language = ForeignLanguage::try_from(standard_library);

        let error = foreign_language.err();
        let expectation = None;
        assert_eq!(error, expectation);
    }
}
